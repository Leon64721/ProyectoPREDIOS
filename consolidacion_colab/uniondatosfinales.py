# MOTOR DE SIMILITUD
# ═══════════════════════════════════════════════════════════════════════════════════
class MotorSimilitud:
    def __init__(self):
        self.modelo = None
        if USAR_IA_SEMANTICA:
            try:
                print("🤖 Cargando modelo IA...")
                self.modelo = SentenceTransformer('paraphrase-multilingual-MiniLM-L12-v2')
                print("✅ Modelo IA listo")
            except Exception as e:
                print(f"⚠️ Sin modelo IA: {e}")

    def sim_nombre(self, a, b):
        score = fuzz.token_set_ratio(a, b)
        if self.modelo:
            try:
                e1 = self.modelo.encode([a])
                e2 = self.modelo.encode([b])
                score = score * 0.6 + cosine_similarity(e1, e2)[0][0] * 100 * 0.4
            except: pass
        return score

    def sim_tipo(self, t1, t2):
        if t1 == t2: return 100.0
        for grupo in [{'NUMERICO','MIXTO'},{'TEXTO','MIXTO'},
                      {'FECHA','TEXTO'},{'BOOLEANO','TEXTO'}]:
            if {t1,t2}.issubset(grupo): return 70.0
        return 0.0

    def score(self, n1, n2, t1, t2):
        sn = self.sim_nombre(n1, n2)
        st = self.sim_tipo(t1, t2)
        return {'score_total': round(sn*PESO_NOMBRE + st*PESO_TIPO, 2),
                'score_nombre': round(sn, 2), 'score_tipo': round(st, 2)}

def conflicto_numerico(a, b):
    n1 = set(re.findall(r'\d{4}', a))
    n2 = set(re.findall(r'\d{4}', b))
    return bool(n1 and n2 and n1 != n2)

