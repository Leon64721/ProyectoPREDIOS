def es_fecha(valor):
    if pd.isna(valor) or valor is None:
        return False
    s = str(valor).strip()
    if not s or s.upper() in ['NAN','NAT','NONE','']:
        return False
    for pat in [r'^\d{1,2}[-/\.]\d{1,2}[-/\.]\d{2,4}$',
                r'^\d{4}[-/\.]\d{1,2}[-/\.]\d{1,2}$',
                r'^\d{2}:\d{2}:\d{2}$',
                r'^\d{4}-\d{2}-\d{2}\s\d{2}:\d{2}',
                r'^\d{1,2}\s+(ENE|FEB|MAR|ABR|MAY|JUN|JUL|AGO|SEP|OCT|NOV|DIC)']:
        if re.match(pat, s, re.IGNORECASE):
            return True
    meses = ['ENE','FEB','MAR','ABR','MAY','JUN','JUL','AGO','SEP','OCT','NOV','DIC',
             'ENERO','FEBRERO','MARZO','ABRIL','MAYO','JUNIO','JULIO','AGOSTO',
             'SEPTIEMBRE','OCTUBRE','NOVIEMBRE','DICIEMBRE',
             'JANUARY','FEBRUARY','MARCH','APRIL','JUNE','JULY','AUGUST',
             'SEPTEMBER','OCTOBER','NOVEMBER','DECEMBER']
    if any(m in s.upper() for m in meses):
        return True
    try:
        pd.to_datetime(s, errors='raise')
        if not re.search(r'\d{2}[-_]\d{3}', s):
            return True
    except:
        pass
    return False

def extraer_rt(valor):
    if isinstance(valor, pd.Series):
        valor = valor.iloc[0] if not valor.empty else None
    if pd.isna(valor) or valor is None:
        return None
    s = str(valor).strip().upper()

    if len(s) < 3 or len(s) > 40:
        return None
    if s.endswith('.0'):
        s = s[:-2]
    if es_fecha(s):
        return None
    if any(p in s for p in ['TOTAL','SUBTOTAL','SUMA','PROMEDIO','AVERAGE']):
        return None

    s = re.sub(r'^(RT|R\.T\.|R\s*T)\s*[-:]?\s*', '', s, flags=re.IGNORECASE).strip()

    if re.match(r'^\d{2,8}([\s\-]*[A-Z0-9]+)*$', s):
        return s

    m = re.search(r'(\d{2}[-_]\d{3,4}[A-Z]?)', s)
    if m: return m.group(1)

    if re.search(r'\d', s) and not s.isdigit():
        if re.search(r'[-_]|\d[A-Z]|[A-Z]\d', s):
            if not re.match(r'^(19|20)\d{2}$', s):
                return s
    return None

def depurar_columna_rt(df, col_rt, umbral_densidad=0.5):
    if col_rt not in df.columns:
        return df
    if isinstance(df[col_rt], pd.DataFrame):
        df = df.loc[:, ~df.columns.duplicated()]

    nuevos_rts = []
    total_cols = len(df.columns)

    for _, fila in df.iterrows():
        val_original = fila[col_rt]
        rt_limpio = extraer_rt(val_original)

        if rt_limpio is not None:
            nuevos_rts.append(rt_limpio)
        else:
            val_str = str(val_original).strip().upper()
            es_vacio = pd.isna(val_original) or val_str in ['NAN', 'NONE', 'NAT', ''] or len(val_str) < 2
            es_invalido = es_fecha(val_str) or any(p in val_str for p in ['TOTAL','SUBTOTAL','SUMA','PROMEDIO','AVERAGE'])

            if not es_vacio and not es_invalido:
                densidad = fila.notna().sum() / total_cols
                if densidad >= umbral_densidad:
                    rt_salvado = re.sub(r'^(RT|R\.T\.|R\s*T)\s*[-:]?\s*', '', val_str, flags=re.IGNORECASE).strip()
                    nuevos_rts.append(rt_salvado)
                else:
                    nuevos_rts.append(None)
            else:
                nuevos_rts.append(None)

    df = df.copy()
    df[col_rt] = nuevos_rts
    df_limpio = df.dropna(subset=[col_rt]).copy()

    diff = len(df) - len(df_limpio)
    if diff > 0:
        print(f"      🧹 {diff} filas eliminadas (Incompletas o sin RT)")

    return df_limpio

