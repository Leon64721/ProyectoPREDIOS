# INFERENCIA DE TIPOS
# ═══════════════════════════════════════════════════════════════════════════════════
def inferir_tipo(serie):
    if serie.empty:
        return 'VACIO'
    muestra = serie.dropna().head(100)
    if muestra.empty:
        return 'VACIO'
    n = es_f = es_b = es_t = 0
    for v in muestra:
        s = str(v).strip()
        if s.upper() in ['SI','NO','TRUE','FALSE','1','0','S','N']:
            es_b += 1; continue
        try:
            float(s.replace(',','').replace('$','').replace('%','')); n += 1; continue
        except: pass
        try:
            pd.to_datetime(s, errors='raise'); es_f += 1; continue
        except: pass
        es_t += 1
    total = len(muestra)
    if n/total > 0.7:      return 'NUMERICO'
    elif es_f/total > 0.6: return 'FECHA'
    elif es_b/total > 0.6: return 'BOOLEANO'
    elif es_t/total > 0.6: return 'TEXTO'
    else:                  return 'MIXTO'

