def limpiar_texto(texto):
    if not isinstance(texto, str):
        return str(texto)
    texto = texto.upper()
    texto = unicodedata.normalize('NFD', texto).encode('ascii', 'ignore').decode('utf-8')
    texto = re.sub(r'[^A-Z0-9\s\.\-_]', ' ', texto)
    for sw in ['CL','KR','CR','DG','AC','AK','NRO','NO','NUM','NUMERO',
               'DE','LA','EL','LOS','LAS','O','Y','DEL','AL']:
        texto = re.sub(f'\\b{sw}\\b', ' ', texto)
    return " ".join(texto.split())

def normalizar_nombre(texto):
    if not isinstance(texto, str):
        return "DESCONOCIDO"
    texto = texto.upper()
    texto = unicodedata.normalize('NFD', texto).encode('ascii', 'ignore').decode('utf-8')
    texto = re.sub(r'[^A-Z0-9]', ' ', texto)
    return " ".join(texto.split())

def detectar_proyecto(ruta_relativa):
    partes = [p for p in ruta_relativa.split(os.sep) if p and p != '.']
    raw    = partes[2] if len(partes) >= 3 else (
             partes[1] if len(partes) >= 2 else (
             partes[0] if len(partes) >= 1 else "PROYECTO_GENERAL"))
    nombre = normalizar_nombre(raw)
    nombre = re.sub(r'\b\d{8}\b', '', nombre)
    nombre = re.sub(r'\b\d{6}\b', '', nombre)
    nombre = re.sub(r'\s+(XLSX|XLS|CSV)$', '', nombre)
    nombre = " ".join(nombre.split())
    return nombre if nombre else normalizar_nombre(raw)

