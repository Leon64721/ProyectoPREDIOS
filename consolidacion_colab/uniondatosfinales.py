def key_hojas(hojas):
    return "|".join(sorted(str(h).strip().lower() for h in hojas))

def hoja_bd_automatica(hojas):
    prioridades = [
        lambda h: str(h).strip().upper() == "BD",
        lambda h: str(h).strip().upper().startswith("BD"),
        lambda h: "BD" in str(h).strip().upper(),
        lambda h: "BASE" in str(h).strip().upper(),
    ]
    for criterio in prioridades:
        for h in hojas:
            if criterio(h):
                return h
    return None

def buscar_en_memoria_hojas(hojas, memoria):
    k = key_hojas(hojas)
    def obtener_nombre_limpio(valor):
        if isinstance(valor, dict):
            return str(valor.get('hoja_seleccionada', '')).strip().lower()
        return str(valor).strip().lower()

    if '__global__' in memoria and k in memoria['__global__']:
        hoja_guardada = obtener_nombre_limpio(memoria['__global__'][k])
        for h in hojas:
            if str(h).strip().lower() == hoja_guardada:
                return h, '__global__'
        if hoja_guardada == "ninguna": return "NINGUNA", '__global__'

    for proyecto, estructuras in memoria.items():
        if proyecto == '__global__': continue
        if k in estructuras:
            hoja_guardada = obtener_nombre_limpio(estructuras[k])
            for h in hojas:
                if str(h).strip().lower() == hoja_guardada:
                    return h, proyecto
            if hoja_guardada == "ninguna": return "NINGUNA", proyecto

    return None, None

def guardar_en_memoria_hojas(hojas, hoja_sel, proyecto, memoria, is_geo=False):
    k = key_hojas(hojas)
    if proyecto not in memoria:
        memoria[proyecto] = {}
    memoria[proyecto][k] = hoja_sel
    if '__global__' not in memoria:
        memoria['__global__'] = {}
    memoria['__global__'][k] = hoja_sel

    if is_geo:
        guardar_memoria_hojas_geo(memoria)
    else:
        guardar_memoria_hojas(memoria)

def seleccionar_hoja(archivo, hojas, proyecto, memoria_hojas):
    hoja_mem, origen = buscar_en_memoria_hojas(hojas, memoria_hojas)
    if hoja_mem:
        return hoja_mem

    hoja_auto = hoja_bd_automatica(hojas)
    if hoja_auto:
        print(f"   ✅ Hoja auto-detectada: '{hoja_auto}' | Proyecto: {proyecto}")
