def fecha_de_archivo(nombre, ruta=None):
    for pat in [r'(\d{2})(\d{2})(\d{4})', r'(\d{4})[-_](\d{2})[-_](\d{2})',
                r'(\d{2})[-_](\d{2})[-_](\d{4})']:
        m = re.search(pat, nombre)
        if m:
            g = m.groups()
            combos = [(g[2],g[1],g[0]), (g[0],g[1],g[2])]
            for y,mo,d in combos:
                try:
                    f = datetime(int(y), int(mo), int(d))
                    if 2000 <= f.year <= 2030:
                        return f
                except:
                    pass
    if ruta and os.path.exists(ruta):
        try:
            return datetime.fromtimestamp(os.path.getmtime(ruta))
        except:
            pass
    return datetime(1900, 1, 1)

