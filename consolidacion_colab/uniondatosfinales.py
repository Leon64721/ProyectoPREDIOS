def calcular_hash_archivo(ruta):
    try:
        stat  = os.stat(ruta)
        clave = f"{ruta}|{stat.st_size}|{stat.st_mtime}"
        return hashlib.md5(clave.encode()).hexdigest()
    except:
        return None

