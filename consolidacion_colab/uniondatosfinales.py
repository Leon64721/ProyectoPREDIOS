def find_drive_file_id_by_name(name, parent_id):
    service = init_drive_service()
    if not service:
        return None
    try:
        query = f"name = '{name.replace("'", "\\'")}' and '{parent_id}' in parents and trashed = false"
        results = service.files().list(q=query, fields='files(id,name)').execute()
        files = results.get('files', [])
        return files[0]['id'] if files else None
    except Exception as e:
        print(f"⚠️ Error buscando archivo en Drive: {e}")
        return None


def download_drive_file_to_local(file_id, destination_path):
    service = init_drive_service()
    if not service:
        return False
    try:
        request = service.files().get_media(fileId=file_id)
        fh = io.FileIO(destination_path, mode='wb')
        downloader = MediaIoBaseDownload(fh, request)
        done = False
        while not done:
            status, done = downloader.next_chunk()
        return True
    except Exception as e:
        print(f"⚠️ Error descargando archivo Drive {file_id}: {e}")
        return False


def upload_local_file_to_drive(local_path, parent_folder_id, existing_file_id=None):
    service = init_drive_service()
    if not service:
        return False
    try:
        media = MediaFileUpload(local_path, resumable=True)
        file_metadata = {'name': os.path.basename(local_path), 'parents': [parent_folder_id]}
        if existing_file_id:
            updated = service.files().update(fileId=existing_file_id, media_body=media).execute()
            return updated.get('id')
        else:
            created = service.files().create(body=file_metadata, media_body=media, fields='id').execute()
            return created.get('id')
    except Exception as e:
        print(f"⚠️ Error subiendo archivo a Drive: {e}")
        return None


