# ✅ FASE 3: CONSOLIDACIÓN (OPTIMIZADA RAM, ORDEN Y FUSIÓN HISTÓRICA)
# ═══════════════════════════════════════════════════════════════════════════════════
def fase3_consolidar():
    print("\n" + "="*80)
    print("🔄 FASE 3: CONSOLIDACIÓN FINAL (OPTIMIZADA EN RAM)")
    print("   ✅ Concatenación iterativa para evitar caídas de memoria")
    print("   ✅ Fusión inteligente de historiales para RTs inactivos")
    print("   ✅ Ordenamiento persistente por Proyecto y RT")
    print("="*80)

    lotes = sorted(glob.glob(os.path.join(RUTA_TEMP, "lote_*.csv")))
    if not lotes:
        print("⚠️ No hay lotes para consolidar")
        return

    print(f"\n📚 Lotes encontrados: {len(lotes)}")

    rts_historicos = set()
    orden_proyectos = {}
    orden_rts = {}
    es_primera_vez = not os.path.exists(RUTA_SALIDA)

    if not es_primera_vez:
        try:
            print("⏳ Leyendo histórico para mantener el orden y detectar RTs nuevos...")
            df_hist = pd.read_csv(RUTA_SALIDA, sep=';', usecols=lambda c: c in [NOMBRE_CLAVE_RT, NOMBRE_CLAVE_PROY], dtype=str, low_memory=False)
            rts_historicos = set(df_hist[NOMBRE_CLAVE_RT].dropna())

            proy_list = df_hist[NOMBRE_CLAVE_PROY].dropna().unique()
            orden_proyectos = {p: i for i, p in enumerate(proy_list)}

            orden_rts = {rt: i for i, rt in enumerate(df_hist[NOMBRE_CLAVE_RT].dropna())}
            del df_hist; gc.collect()
        except Exception as e:
            print(f"   ⚠️ No se pudo leer el histórico de ordenamiento: {e}")
            es_primera_vez = True

    print(f"\n🔗 Concatenando y fusionando historiales de {len(lotes)} lotes paso a paso...")
    df_final = pd.DataFrame()
    total_antes = 0

    for i, f in enumerate(lotes, 1):
        print(f"   [{i}/{len(lotes)}] Procesando: {os.path.basename(f)}", end='\r')
        try:
            df_temp = pd.read_csv(f, sep=';', encoding='utf-8-sig', low_memory=False)
            total_antes += len(df_temp)

            if 'FECHA_ARCHIVO' in df_temp.columns:
                df_temp['FECHA_ARCHIVO'] = pd.to_datetime(df_temp['FECHA_ARCHIVO'], errors='coerce').fillna(pd.Timestamp('1900-01-01'))

            df_final = pd.concat([df_final, df_temp], ignore_index=True)
            del df_temp

            # 🚨 CIRUGÍA: Fusionar incrementalmente para liberar RAM en bucle
            if i % 3 == 0 or i == len(lotes):
                df_final.sort_values('FECHA_ARCHIVO', ascending=False, inplace=True, na_position='last')
                # En lugar de eliminar duplicados, agrupamos y tomamos el primer valor no nulo de cada columna
                df_final = df_final.groupby(NOMBRE_CLAVE_RT, as_index=False, sort=False).first()
                gc.collect()

        except Exception as e:
            print(f"\n   ⚠️ Error leyendo {f} → {e}")

    if df_final.empty:
        print("\n❌ El dataframe final está vacío")
        return

    rts_final = df_final[NOMBRE_CLAVE_RT].nunique()
    total_final = len(df_final)
    eliminados = total_antes - total_final

    print(f"\n\n✅ FUSIÓN Y DEDUPLICACIÓN COMPLETADA:")
    print(f"   Pool histórico/bruto:   ~{total_antes:,} registros procesados")
    print(f"   RTs únicos finales:      {rts_final:,}")
    print(f"   Filas fusionadas/elim.:  {eliminados:,}")

    if es_primera_vez:
        df_final['CONTROL_NUEVO'] = ''
    else:
        df_final['CONTROL_NUEVO'] = df_final[NOMBRE_CLAVE_RT].apply(lambda x: 'NUEVO' if x not in rts_historicos else '')

    print("📏 Restaurando orden de proyectos...")
    nuevos_proys = sorted([p for p in df_final[NOMBRE_CLAVE_PROY].dropna().unique() if p not in orden_proyectos])
    max_idx = max(orden_proyectos.values()) if orden_proyectos else 0
    for p in nuevos_proys:
        max_idx += 1
        orden_proyectos[p] = max_idx

    df_final['_ORD_PROY'] = df_final[NOMBRE_CLAVE_PROY].map(orden_proyectos).fillna(999999)
    df_final['_ORD_RT'] = df_final[NOMBRE_CLAVE_RT].map(orden_rts).fillna(999999999)

    df_final.sort_values(['_ORD_PROY', '_ORD_RT', 'FECHA_ARCHIVO'], ascending=[True, True, True], inplace=True)
    df_final.drop(columns=['_ORD_PROY', '_ORD_RT'], inplace=True)
    df_final.reset_index(drop=True, inplace=True)
    gc.collect()

    prio = [NOMBRE_CLAVE_RT, NOMBRE_CLAVE_PROY, 'FECHA_ARCHIVO', 'ARCHIVO_ORIGEN']
    prio_ok = [c for c in prio if c in df_final.columns]

    columnas_finales = ['INACTIVO/ACTIVO', 'OBSERVACIÓN INACTIVO/ACTIVO', 'CONTROL_NUEVO']
    otras = sorted([c for c in df_final.columns if c not in prio and c not in columnas_finales])
    finales_ok = [c for c in columnas_finales if c in df_final.columns]

    df_final = df_final[prio_ok + otras + finales_ok]

    print(f"\n💾 Guardando {RUTA_SALIDA}...")
    df_final.to_csv(RUTA_SALIDA, sep=';', index=False, encoding='utf-8-sig')
    tam = os.path.getsize(RUTA_SALIDA) / (1024*1024)
    print(f"   ✅ {tam:.2f} MB")

    with open(RUTA_REPORT_TXT, 'w', encoding='utf-8') as f:
        f.write("="*80 + "\nREPORTE V21.0 — REANUDABLE + SIN PÉRDIDA DE RTs\n" + "="*80 + "\n\n")
        f.write(f"Fecha:    {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")
        f.write(f"Pool global:       {total_antes:,}\n")
        f.write(f"Registros únicos:  {total_final:,}\n")
        f.write(f"Duplicados elim.:  {eliminados:,}\n")
        f.write(f"RTs únicos:        {rts_final:,}\n")
        f.write(f"Columnas:          {len(df_final.columns)}\n")
        f.write(f"Tamaño:            {tam:.2f} MB\n\n")
        f.write("COLUMNAS:\n" + "─"*60 + "\n")
        for i, col in enumerate(df_final.columns, 1):
            pct = df_final[col].notna().sum() / len(df_final) * 100
            f.write(f"  {i:3d}. {col:<50} ({pct:5.1f}%)\n")
        if NOMBRE_CLAVE_PROY in df_final.columns:
            f.write("\nPOR PROYECTO:\n" + "─"*60 + "\n")
            for proy, grp in df_final.groupby(NOMBRE_CLAVE_PROY):
                f.write(f"  {proy}: {len(grp):,} registros | {grp[NOMBRE_CLAVE_RT].nunique():,} RTs\n")
    print(f"   ✅ Reporte: {RUTA_REPORT_TXT}")

    # ═══════════════════════════════════════════════════════════════════════════════════
    # 🚨 AUDITORÍA DE GEOREFERENCIACIÓN
    # ═══════════════════════════════════════════════════════════════════════════════════
    print("\n" + "="*80)
    print("🔎 AUDITORÍA DE 100% RTs DE GEOREFERENCIACIÓN")
    print("="*80)
    audit_geo_cache = cargar_json(RUTA_AUDITORIA_GEO, [])
    rts_geo_totales = set(audit_geo_cache)
    rts_consolidados = set(df_final[NOMBRE_CLAVE_RT].dropna().unique())

    rts_faltantes = rts_geo_totales - rts_consolidados

    if len(rts_geo_totales) == 0:
        print("   ℹ️ No se detectaron RTs en hojas de georreferenciación.")
    elif len(rts_faltantes) == 0:
        print(f"   ✅ AUDITORÍA EXITOSA: El 100% de los RTs de GEO ({len(rts_geo_totales):,}) están en el consolidado final.")
    else:
        print(f"   ❌ ADVERTENCIA: Faltan {len(rts_faltantes):,} RTs de GEO en el archivo final.")
        print(f"      Ejemplos faltantes: {list(rts_faltantes)[:5]}")

    resp = input("\n🧹 ¿Eliminar lotes temporales? (s/n): ").lower().strip()
    if resp == 's':
        for lt in lotes:
            try: os.remove(lt)
            except: pass
        if os.path.exists(RUTA_PROGRESO):
            os.remove(RUTA_PROGRESO)
        print(f"   ✅ Lotes y progreso eliminados")
    else:
        print(f"   ℹ️ Conservados en: {RUTA_TEMP}")

    print(f"\n{'='*80}\n🎉 CONSOLIDACIÓN COMPLETADA")
    print(f"   ✅ Registros: {total_final:,} | RTs: {rts_final:,} | Columnas: {len(df_final.columns)}")
    del df_final; gc.collect()

